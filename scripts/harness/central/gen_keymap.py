"""The keymap of a ZMK build's zephyr.dts as a C table, for the central
harness of src/layer.c (harness_central.c): each layer's bindings, the
behavior by the device name a binding carries (DEVICE_DT_NAME: the node's
label property, else its full name) and its two parameters, in key position
order; and the names of the &none and &trans nodes. canon_keymap.h is this
output for canon's Imprint Dongle (canon's `./scripts/build-zmk.sh
imprint_dongle` leaves the file under its west topdir):

    python3 -I gen_keymap.py \
        ~/.cache/zmk-canon/cfgrepo/build/imprint_dongle/zephyr/zephyr.dts \
        > canon_keymap.h

The header line names the file by its last four path components only, so
the output carries no home directory.
"""
import re
import sys


def main():
    text = open(sys.argv[1], encoding="utf-8").read()
    lines = text.splitlines()
    head = re.compile(r"^\s*((?:[A-Za-z_][\w]*:\s*)+)?([\w][\w,.+-]*(?:@[\w]+)?)\s*\{\s*$")
    stack = []  # (labels, name, props)
    nodes = []
    for line in lines:
        m = head.match(line)
        if m:
            labels = re.findall(r"([A-Za-z_]\w*):", m.group(1) or "")
            stack.append({"labels": labels, "name": m.group(2), "props": {}, "path": [s["name"] for s in stack] + [m.group(2)]})
            continue
        if re.match(r"^\s*\};\s*$", line):
            if stack:
                nodes.append(stack.pop())
            continue
        if stack:
            p = re.match(r"^\s*([#\w,.-]+)\s*=\s*(.*);\s*$", line)
            if p:
                stack[-1]["props"][p.group(1)] = p.group(2)
    by_label = {}
    for n in nodes:
        for lab in n["labels"]:
            by_label[lab] = n

    def cells(node):
        v = node["props"].get("#binding-cells", "< 0x0 >")
        return int(re.search(r"0x[0-9a-fA-F]+|\d+", v).group(0), 0)

    def devname(node):
        lab = node["props"].get("label")
        if lab:
            return lab.strip().strip('"')
        return node["name"]

    keymap = [n for n in nodes if n["props"].get("compatible", "").strip() == '"zmk,keymap"']
    if len(keymap) != 1:
        sys.exit("one zmk,keymap node expected, found %d" % len(keymap))
    km_path = keymap[0]["path"]
    layers = [n for n in nodes if n["path"][:-1] == km_path and "bindings" in n["props"]]
    out = []
    width = None
    for layer in layers:
        toks = layer["props"]["bindings"].strip()
        toks = toks.strip("<>").replace(">, <", " ").replace("> , <", " ").split()
        row = []
        i = 0
        while i < len(toks):
            t = toks[i]
            if not t.startswith("&"):
                sys.exit("unexpected token %r in layer %s" % (t, layer["name"]))
            node = by_label[t[1:]]
            n = cells(node)
            params = [int(x, 0) for x in toks[i + 1:i + 1 + n]]
            params += [0] * (2 - len(params))
            row.append((devname(node), params[0], params[1]))
            i += 1 + n
        if width is None:
            width = len(row)
        elif width != len(row):
            sys.exit("layer %s has %d bindings, not %d" % (layer["name"], len(row), width))
        out.append((layer["props"].get("display-name", '"%s"' % layer["name"]).strip(), row))
    inert = [devname(n) for n in nodes
             if n["props"].get("compatible", "").strip() in ('"zmk,behavior-none"', '"zmk,behavior-transparent"')]
    print("/* generated by gen_keymap.py from %s */" % "/".join(sys.argv[1].split("/")[-4:]))
    print("#define CANON_LAYERS %d" % len(out))
    print("#define CANON_KEYS %d" % width)
    print("static const char *const canon_layer_names[CANON_LAYERS] = {%s};" % ", ".join(name for name, _ in out))
    print("static const struct zmk_behavior_binding canon_keymap[CANON_LAYERS][CANON_KEYS] = {")
    for name, row in out:
        print("    { /* %s */" % name)
        for dev, p1, p2 in row:
            print('        {.behavior_dev = "%s", .param1 = 0x%x, .param2 = 0x%x},' % (dev, p1, p2))
        print("    },")
    print("};")
    print("static const char *const canon_inert[] = {%s};" % ", ".join('"%s"' % n for n in inert))


main()
